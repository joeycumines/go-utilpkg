package strings

// ByteNumber is a numeric type that represents the amount
// of bytes in a string, array or slice.
type ByteNumber int

// RuneNumber is a numeric type that represents the amount
// of runes in a string, array or slice.
type RuneNumber int

// GraphemeNumber is a numeric type that represents the amount
// of grapheme clusters in a string, array or slice.
type GraphemeNumber int

// Width is a numeric type that represents the visible
// width of characters in a string as seen in a terminal emulator.
type Width int
